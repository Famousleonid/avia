-- Final verification result sets.
SELECT COUNT(*) AS active_components FROM components
WHERE manual_id = @avia_manual_id AND deleted_at IS NULL;
SELECT 'log_card' AS flag, COUNT(*) AS source_rows FROM avia_m95_flags WHERE log_card = 1
UNION ALL SELECT 'ndt_list', COUNT(*) FROM avia_m95_flags WHERE ndt_list = 1
UNION ALL SELECT 'cad_list', COUNT(*) FROM avia_m95_flags WHERE cad_list = 1
UNION ALL SELECT 'paint_list', COUNT(*) FROM avia_m95_flags WHERE paint_list = 1
UNION ALL SELECT 'kit', COUNT(*) FROM avia_m95_flags WHERE kit = 1;
SELECT COUNT(*) AS reviewed_service_bulletins FROM avia_m95_sb_defs;
SELECT g.type, COUNT(*) AS groups_count
FROM manual_part_groups AS g INNER JOIN avia_m95_group_defs AS d ON d.code = g.code
WHERE g.manual_id = @avia_manual_id AND g.deleted_at IS NULL GROUP BY g.type ORDER BY g.type;
SELECT g.code, g.name, g.type, o.ipl_num, o.part_number,
       SUM(cov.component_id IS NOT NULL) AS direct_rows,
       SUM(cov.covered_manual_part_group_option_id IS NOT NULL) AS nested_rows
FROM manual_part_groups AS g
INNER JOIN manual_part_group_options AS o ON o.manual_part_group_id = g.id AND o.is_default = 1 AND o.deleted_at IS NULL
LEFT JOIN manual_part_group_coverages AS cov ON cov.manual_part_group_option_id = o.id
WHERE g.manual_id = @avia_manual_id AND g.behavior = 'bundle' AND g.deleted_at IS NULL
GROUP BY g.code, g.name, g.type, o.ipl_num, o.part_number ORDER BY g.code;

