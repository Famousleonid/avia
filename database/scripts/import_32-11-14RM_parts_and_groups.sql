  INNER JOIN manual_part_groups AS cg ON cg.code = d.child_group_code
  INNER JOIN manual_part_group_options AS co ON co.manual_part_group_id = cg.id AND co.is_default = 1 AND co.deleted_at IS NULL
  INNER JOIN manual_part_group_coverages AS cov ON cov.manual_part_group_option_id = o.id AND cov.covered_manual_part_group_option_id = co.id
);
SET @avia_assert_sql := IF(@avia_group_count = 114 AND @avia_option_count = 296
  AND @avia_direct_count = 245 AND @avia_nested_count = 133,
  'SELECT 1 AS final_counts_ok', 'SELECT * FROM AVIA_ABORT_FINAL_COUNTS_MISMATCH');
PREPARE avia_assert_stmt FROM @avia_assert_sql;
EXECUTE avia_assert_stmt;
DEALLOCATE PREPARE avia_assert_stmt;
