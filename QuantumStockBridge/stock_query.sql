SELECT pm.PNM_AUTO_KEY, pm.PN, pm.DESCRIPTION,
       NVL(pm.QTY_OH,0) QTY_OH, NVL(pm.QTY_RESERVED,0) QTY_RESERVED,
       NVL(pm.QTY_AVAILABLE,0) QTY_AVAILABLE, r.WO_NUMBER, r.ALLOCATED_QTY
FROM QCTL.PARTS_MASTER pm
LEFT JOIN (
    SELECT s.PNM_AUTO_KEY, wo.SI_NUMBER WO_NUMBER, SUM(sr.QTY_RESERVED) ALLOCATED_QTY
    FROM QCTL.STOCK_RESERVATIONS sr
    JOIN QCTL.STOCK s ON s.STM_AUTO_KEY=sr.STM_AUTO_KEY
    LEFT JOIN QCTL.WO_BOM wb ON wb.WOB_AUTO_KEY=sr.WOB_AUTO_KEY
    LEFT JOIN QCTL.SO_DETAIL sd ON sd.SOD_AUTO_KEY=sr.SOD_AUTO_KEY
    LEFT JOIN QCTL.WO_BOM swb ON swb.WOB_AUTO_KEY=sd.WOB_AUTO_KEY
    LEFT JOIN QCTL.RO_DETAIL rd ON rd.ROD_AUTO_KEY=sr.ROD_AUTO_KEY
    LEFT JOIN QCTL.WO_BOM rwb ON rwb.WOB_AUTO_KEY=rd.WOB_AUTO_KEY
    LEFT JOIN QCTL.WO_OPERATION wo ON wo.WOO_AUTO_KEY=COALESCE(sr.WOO_AUTO_KEY,wb.WOO_AUTO_KEY,sd.WOO_AUTO_KEY,swb.WOO_AUTO_KEY,rwb.WOO_AUTO_KEY)
    WHERE sr.QTY_RESERVED>0
    GROUP BY s.PNM_AUTO_KEY,wo.SI_NUMBER
) r ON r.PNM_AUTO_KEY=pm.PNM_AUTO_KEY
ORDER BY pm.PN,pm.PNM_AUTO_KEY,r.WO_NUMBER
